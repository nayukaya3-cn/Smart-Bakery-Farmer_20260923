def readiness_posterior(done: int, total: int, prior_a: float = 1.0, prior_b: float = 1.0,
                        threshold: float = 0.7, n_draws: int = 20000, seed: int = 0) -> dict:
    """準備度をベータ分布でベイズ推定する。

    事前分布 Beta(a, b) に「できた課題 done ／ 出された課題 total」を足して事後分布を作り、
    平均・80%区間・「準備度が threshold 以上である確率」を返す。
    課題の数が少ないうちは区間が広い ＝ まだ判断材料が少ない、と読む。
    """
    if total < 0 or not (0 <= done <= total):
        raise ValueError("できた課題の数は 0 以上・出された課題の数以下にしてください")
    a, b = prior_a + done, prior_b + (total - done)
    draws = np.random.default_rng(seed).beta(a, b, n_draws)
    lo, hi = np.quantile(draws, [0.1, 0.9])
    return dict(mean=a / (a + b), lo=float(lo), hi=float(hi),
                p_ready=float((draws >= threshold).mean()), a=a, b=b)



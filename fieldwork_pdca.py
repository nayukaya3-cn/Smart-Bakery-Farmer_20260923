def rank_for_coaching(log: pd.DataFrame, threshold: float = 0.7) -> pd.DataFrame:
    """準備度の事後確率が低い順に並べ、声かけの優先順位をつける。"""
    rows = []
    for _, r in log.iterrows():
        post = readiness_posterior(int(r["できた課題"]), int(r["出された課題"]), threshold=threshold)
        if int(r["作った問い"]) == 0:
            hint = COACHING[0]
        elif int(r["出典を書いた数値"]) == 0:
            hint = COACHING[2]
        elif post["mean"] < 0.5:
            hint = COACHING[1]
        else:
            hint = COACHING[4]
        rows.append({"生徒ID": r["生徒ID"], "準備度（平均）": round(post["mean"], 2),
                     "80%区間": f"{post['lo']:.2f}〜{post['hi']:.2f}",
                     f"準備度≧{threshold:.0%}の確率": round(post["p_ready"], 2),
                     "見立て": hint[0], "声かけの例": hint[1]})
    out = pd.DataFrame(rows)
    return out.sort_values(f"準備度≧{threshold:.0%}の確率").reset_index(drop=True)



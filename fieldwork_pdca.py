def risk_level(likelihood: int, severity: int) -> tuple[int, str]:
    """リスク点と区分を返す。6以上は CCP、3〜4 は前提条件（PRP）、2以下は様子を見る。

    重大さ3（命・健康・個人情報）の危害は、起こりやすさが1でも CCP 候補として残す
    （HACCPの判断樹で「この工程でしか防げない重大な危害」を外さないのと同じ考え方）。
    """
    if not (1 <= likelihood <= 3 and 1 <= severity <= 3):
        raise ValueError("起こりやすさ・重大さは 1〜3 で入れてください")
    score = int(likelihood) * int(severity)
    if score >= 6 or severity == 3:
        return score, "CCP（本番で管理）"
    if score >= 3:
        return score, "前提条件（事前に整える）"
    return score, "様子を見る"


def analyze_hazards(df: pd.DataFrame) -> pd.DataFrame:
    """危害の表にリスク点と区分を足し、点の高い順に並べる。"""
    out = df.copy()
    res = [risk_level(int(a), int(b)) for a, b in zip(out["起こりやすさ"], out["重大さ"])]
    out["リスク点"] = [r[0] for r in res]
    out["区分"] = [r[1] for r in res]
    return out.sort_values(["リスク点", "重大さ"], ascending=False).reset_index(drop=True)



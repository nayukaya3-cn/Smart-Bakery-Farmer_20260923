def diagnose_multiple(answer: float, inv: pd.DataFrame) -> tuple[bool, str]:
    """「指定数量の倍数はいくつ？」への答えを、間違い方に合わせて返す。"""
    res = designated_multiple(inv)
    right = res["total"]
    tbl = res["table"]
    if np.isclose(answer, right, rtol=0.02, atol=0.002):
        return True, f"正解。品ごとに「保管量 ÷ 指定数量」を出して足す。合計 {right:.3f}。"
    if len(tbl) and np.isclose(answer, tbl["保管量"].sum() / tbl["指定数量"].sum(), rtol=0.02):
        return False, "量を全部足してから、指定数量も全部足して割っています。指定数量が違う品は、先に1つずつ割ってから足す。"
    if len(tbl) and np.isclose(answer, (tbl["指定数量"] / tbl["保管量"]).sum(), rtol=0.02):
        return False, "割る向きが逆です。もとにする量（分母）は指定数量。"
    if np.isclose(answer, right * 100, rtol=0.02):
        return False, "％で答えています。倍数は割合（1 で指定数量ちょうど）。"
    return False, "もう一度。倍数 = (品A の量 ÷ 品A の指定数量) + (品B の量 ÷ 品B の指定数量) + …"



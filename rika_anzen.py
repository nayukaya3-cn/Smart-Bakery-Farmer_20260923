def designated_multiple(inv: pd.DataFrame) -> dict:
    """指定数量の倍数 = Σ（保管量 ÷ 指定数量）。品名が違う危険物は商を足し合わせる。

    同じ消防法区分の品（エタノールと消毒用エタノールなど）は、量を合算してから割るのと同じ結果になる。
    """
    rows = []
    for _, r in inv.iterrows():
        name, q = r["品名"], r["保管量"]
        if name not in DESIGNATED or pd.isna(q) or q <= 0:
            continue
        cls, limit, unit = DESIGNATED[name]
        rows.append((name, cls, float(q), unit, limit, float(q) / limit))
    tbl = pd.DataFrame(rows, columns=["品名", "区分", "保管量", "単位", "指定数量", "倍数"])
    total = float(tbl["倍数"].sum()) if len(tbl) else 0.0
    return {"table": tbl, "total": total, "status": storage_status(total)}


def storage_status(total: float) -> str:
    """倍数の合計から、法の扱いを言葉にする。"""
    if total >= 1:
        return "許可"        # 指定数量以上：許可を受けた貯蔵所でなければ置けない
    if total >= SMALL_QTY_RATIO:
        return "届出"        # 少量危険物：所轄の消防署へ届出（市町村条例）
    return "条例の基準"      # 1/5 未満でも、火気・整理整頓・容器の基準は守る



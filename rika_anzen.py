def diluted_percent(stock_pct: float, stock_g: float, water_g: float) -> float:
    """原液 stock_g に水 water_g を加えたあとの質量パーセント濃度。分母は溶液全体。"""
    total = stock_g + water_g
    if total <= 0:
        raise ValueError("溶液の質量が0")
    return stock_pct * stock_g / total


def diluted_percent_by_volume(name: str, stock_ml: float, water_ml: float) -> float:
    """体積で「原液 : 水」を混ぜたときの質量％（水の密度 1.00 g/mL）。"""
    pct, rho, _, _ = STOCK[name]
    return diluted_percent(pct, stock_ml * rho, water_ml * 1.00)


def molarity(pct: float, density: float, molar_mass: float) -> float:
    """質量％ → モル濃度 [mol/L]（高校 化学基礎）。1 L の溶液の質量 × 割合 ÷ モル質量。"""
    return 1000 * density * pct / 100 / molar_mass


def is_gekibutsu(name: str, pct: float) -> bool:
    """毒劇法の濃度の線を「超える」なら劇物。"""
    return pct > STOCK[name][3]


def max_water_ratio_still_gekibutsu(name: str) -> float:
    """体積で何倍の水までなら、まだ劇物か（水:原液 = x:1 の x の上限）。"""
    pct, rho, _, line = STOCK[name]
    # pct*rho / (rho + x) = line  →  x = rho*(pct/line - 1)
    return max(rho * (pct / line - 1), 0.0)


